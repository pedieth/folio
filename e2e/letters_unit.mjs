// unit test for src/letters.mjs: privacy + flow. node e2e/letters_unit.mjs
import { makeD1 } from "./d1shim.mjs";
import { handleLetters } from "../src/letters.mjs";
import { createHash } from "node:crypto";
const env = { DB: makeD1() };
const sha = s => createHash("sha256").update(s).digest("hex");
let bad = 0; const ok = (c, m) => { console.log((c ? "PASS " : "FAIL ") + m); if (!c) bad++; };
const call = async (route, fid, body, method = "POST") => {
  const r = await handleLetters(new Request("https://x/api/letters/" + route, { method, headers: { "content-type": "application/json" }, body: method === "POST" ? JSON.stringify(body || {}) : undefined }), env, async () => fid);
  return { s: r.status, j: await r.json() };
};
const T = "this is a long enough letter about something i never told anyone at all";
const k1 = "a".repeat(64), k2 = "b".repeat(64);
ok((await handleLetters(new Request("https://x/api/feed"), env, async () => 1)) === null, "other routes untouched");
ok((await call("write", 0, { body: T, mbox_hash: sha(k1) })).s === 401, "write needs sign-in");
ok((await call("write", 11, { body: "short", mbox_hash: sha(k1) })).j.error === "length", "min length");
ok((await call("write", 11, { body: T + " mail me a@b.co", mbox_hash: sha(k1) })).j.error === "pii", "email blocked");
ok((await call("write", 11, { body: T + " @dwr", mbox_hash: sha(k1) })).j.error === "pii", "handle blocked");
ok((await call("write", 11, { body: "sometimes i want to die and nobody notices it", mbox_hash: sha(k1) })).j.error === "crisis", "crisis not published");
const w = await call("write", 11, { body: T, tag: "pain", mbox_hash: sha(k1) });
ok(w.s === 200 && w.j.id, "write ok");
ok((await call("write", 11, { body: T, mbox_hash: sha(k1) })).j.error === "quota", "one a day");
const row = await env.DB.prepare("SELECT * FROM letters").first();
ok(!Object.keys(row).some(c => /fid|user|name|created/.test(c)) && !Object.values(row).includes(11), "letter row has no fid/name/time");
ok(row.publish_at % 3600 === 0, "publish time rounded to the hour");
await env.DB.prepare("UPDATE letters SET publish_at=?").bind(Math.floor(Date.now() / 1000) - 10).run();
ok((await call("inbox", 22, {})).j.locked === true, "inbox locked until you write");
await call("write", 22, { body: T + " two", mbox_hash: sha(k2) });
const ib = await call("inbox", 22, {});
ok(ib.j.letters.length === 1 && ib.j.letters[0].id === w.j.id, "reader gets stranger's letter");
const ib11 = await call("inbox", 11, { exclude: [w.j.id] });
ok(!ib11.j.letters.some(l => l.id === w.j.id), "never your own letter");
ok((await call("hug", 33, { id: w.j.id })).s === 404, "hug only letters delivered to you");
await call("hug", 22, { id: w.j.id }); await call("hug", 22, { id: w.j.id });
const mine = await call("mine", 0, { keys: [k1] });
ok(mine.j.letters.length === 1 && mine.j.letters[0].hugs === 1, "my letters by key, no sign-in, hug counted once");
ok((await call("mine", 0, { keys: [k2.replace(/b/g, "c")] })).j.letters.length === 0, "wrong key sees nothing");
ok((await call("stats", 0, null, "GET")).s === 200, "stats");
process.exit(bad ? 1 : 0);
